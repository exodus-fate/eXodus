"""
Writes docs/SOURCE_BUNDLE.md: every source file of the project in one
Markdown document (path headings + fenced code), for an assistant that can't
read the repository directly. Regenerate after changing code:

    python3 scripts/bundle_source.py

Binary audio banks are left out (they are generated by scripts/audio/); the map
of where each sound sits is included as src/shared/Config/AudioBank.luau.
"""

import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "docs", "SOURCE_BUNDLE.md")

TOP_FILES = ["default.project.json", "rokit.toml", "selene.toml", "stylua.toml", ".gitignore"]
TREES = ["src", "tests", "scripts"]
LANG = {".luau": "lua", ".py": "python", ".sh": "bash", ".json": "json", ".toml": "toml"}


def collect():
    files = [f for f in TOP_FILES if os.path.exists(os.path.join(ROOT, f))]
    for tree in TREES:
        for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, tree)):
            dirnames[:] = sorted(d for d in dirnames if d != "__pycache__")
            for name in sorted(filenames):
                if os.path.splitext(name)[1] in LANG:
                    files.append(os.path.relpath(os.path.join(dirpath, name), ROOT))
    return files


def main():
    files = collect()
    sections, toc, total = [], [], 0
    for rel in files:
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            text = f.read()
        lines = text.count("\n") + 1
        total += lines
        anchor = rel.lower().replace("/", "").replace(".", "").replace("_", "")
        toc.append("- [`%s`](#%s) (%d lines)" % (rel, anchor, lines))
        fence = "````" if "```" in text else "```"
        lang = LANG.get(os.path.splitext(rel)[1], "")
        sections.append("## %s\n\n%s%s\n%s\n%s\n" % (rel, fence, lang, text.rstrip("\n"), fence))
    header = [
        "# DEAD AIR: CHANNEL ZERO — complete source bundle",
        "",
        "Generated by `scripts/bundle_source.py`. Every source file in the repository,",
        "in order: project config, `src/` (the game), `tests/` (Lune test suite and",
        "mock engine), `scripts/` (build, bake, audio synthesis). %d files, %d lines." % (len(files), total),
        "Read `docs/AI_HANDOFF.md` first; it explains how these fit together.",
        "",
        "## Files",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(header + toc) + "\n\n" + "\n".join(sections))
    print("Wrote %s: %d files, %d lines, %.0f KB" % (os.path.relpath(OUT, ROOT), len(files), total, os.path.getsize(OUT) / 1024))


if __name__ == "__main__":
    main()
